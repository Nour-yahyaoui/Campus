#!/usr/bin/env node
/**
 * Embeds `migrations/*.sql` into `packages/core/src/migrations.generated.ts`.
 *
 * Why: `/api/initialize` has to work on hosts that ship only the built app, not
 * the repository — a Vercel function bundle, a Docker image, a serverless
 * runtime. Reading `../../migrations` from disk is not guaranteed there, and a
 * deploy that cannot create its own schema is exactly the failure this route
 * exists to prevent. The CLI (`scripts/db.mjs`) keeps reading the files, and a
 * test asserts both copies agree, so neither can drift silently.
 *
 *   npm run db:embed-migrations
 *
 * Run this after adding or editing a migration, then commit the result.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(root, "migrations");
const target = path.join(root, "packages", "core", "src", "migrations.generated.ts");

const names = (await readdir(migrationsDir)).filter((name) => name.endsWith(".sql")).sort();
if (names.length === 0) {
  console.error(`No .sql files in ${migrationsDir}`);
  process.exit(1);
}

const entries = [];
for (const name of names) {
  const sql = await readFile(path.join(migrationsDir, name), "utf8");
  const checksum = createHash("sha256").update(sql).digest("hex");
  // JSON.stringify handles quotes, newlines, backticks and ${ in the SQL.
  entries.push(`  { name: ${JSON.stringify(name)}, checksum: ${JSON.stringify(checksum)}, sql: ${JSON.stringify(sql)} },`);
}

const output = `// Generated by scripts/embed-migrations.mjs — do not edit by hand.
// Run \`npm run db:embed-migrations\` after changing anything in migrations/.
// The checksums below are identical to the ones the CLI writes to
// schema_migrations, so a database created through /api/initialize and one
// created by \`npm run db:migrate\` are indistinguishable afterwards.

export interface EmbeddedMigration {
  name: string;
  checksum: string;
  sql: string;
}

export const EMBEDDED_MIGRATIONS: EmbeddedMigration[] = [
${entries.join("\n")}
];
`;

await writeFile(target, output, "utf8");
console.log(`embedded ${names.length} migrations -> ${path.relative(root, target)}`);
